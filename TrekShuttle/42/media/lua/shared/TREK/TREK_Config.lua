-- Whether a new world starts with the shields up. They can be lowered and
-- raised from the helm; there is deliberately no radius control, only the
-- state. The setting is saved with the world, so this is only the default.
C.ShieldsDefault = true

---------------------------------------------------------------------------
-- The transporter
---------------------------------------------------------------------------
-- Beaming is the shuttle's own trick and is deliberately not gated on the
-- ship being anywhere in particular: when it is not sitting on the ground it
-- is overhead, and the pad reaches you either way.
--
-- The delay is flavour with a purpose -- an instant snap reads as a debug
-- teleport, and a second and a half of dematerialising reads as a transporter
-- and gives the halo note time to be seen. Ticks.
C.BeamDelay = 90

-- How far a beam-down may miss by when the exact square is occupied.
C.BeamScatter = 6

-- Transporter charges. On a server whose speed anti-cheat kicks or bans
-- (AntiCheatSpeed 1 or 2), every long move of a character is one strike and
-- four uncleared strikes remove the player; one strike clears every 150
-- seconds. So each player gets that budget as charges, and the fourth beam is
-- refused in lore ("recharging") instead of the server kicking them. Single
-- player, and servers that only log or ignore the check, are unlimited.
C.TransporterCharges       = 3
C.TransporterRechargeSecs  = 150

---------------------------------------------------------------------------
-- Flight: the sky plane
---------------------------------------------------------------------------
-- The shuttle flies by *driving*, on an invisible floor the mod lays at
-- altitude. This is not a flourish, it is the only thing build 42 allows.
--
-- BaseVehicle.update() sets a vehicle's z to 0 every single tick, and then
-- puts it back to its physics level only if a floor tile exists under the
-- vehicle's centre square at that level (or the one below). Everything that
-- matters reads that clamped z: the render camera, where the occupants are
-- drawn, isIntersectingSquare, breakingObjects/damageObjects, and -- on every
-- other player's machine -- clientUpdateVehiclePos, which writes setZ(0)
-- outright. Lifting the physics body alone therefore gives a ship that flies
-- in the physics engine and sits on the ground in the game, ploughing through
-- fences as it goes. That was tried on paper and disproved from the bytecode
-- before a line of it was written (PILOTING.md section 5.1).
--
-- Put a floor there and the whole problem dissolves: the z is legitimate, so
-- the ship and its crew are drawn in the air; collision resolves at the flight
-- level, so it passes over a two-storey building instead of demolishing it;
-- the wheels have something to rest on, so the engine's own physics drives it
-- and no part of this mod has to fight gravity; and because the floor holds
-- the ship up, nothing falls out of the sky when the pilot leaves the seat.
--
-- The tile is vanilla. invisible_01_0's only two properties are attachedFloor
-- and solidfloor: a floor that is solid and cannot be seen.
C.SkyTile = "invisible_01_0"

-- Bullet units per z level, read straight out of BaseVehicle.setDebugZ's
-- bytecode: it computes fastfloor(origin.y / 2.4494900703430176). Three times
-- 0.8164966702461243 is the same number; both constants are in that method.
C.LevelUnits = 2.4494900703430176

-- How far around the ship the plane extends, in squares.
--
-- Deliberately small, and it was not always. A floor is a floor: the engine
-- treats everything under one as being indoors and stops drawing the ground
-- below it, so a wide plane put a disc of blackness around the ship and hid
-- the very world she was flying over. Seen in game, 2026-09-17 -- "I can see
-- the world but near me is a sphere of blackness."
--
-- The hull is 3 by 5, so 2 squares out is a 5 by 5 patch: the smallest that
-- still covers her at any heading and gives the wheels something under them.
--
-- This is the only real lever on the darkness. A floor darkens whatever is
-- beneath it and nothing can stop that, so the patch has to be small enough
-- that the hull is drawn over it. It was 16, then 4, then 3, and at 3 with a
-- square of margin the kept area was a 9 by 9 box -- 81 squares of shadow
-- around a hull that covers 15, which is the "trailing dark blotch". 5 by 5 is
-- 25 against the hull's 15, so what is left is a one-square rim under her
-- rather than a wake behind her.
C.SkyRadius = 2

-- No margin at all: a square is lifted the moment she is not over it. The
-- margin existed so she was never chasing her own floor, but the paver
-- recentres every tick and lays the centre square first, so there is nothing
-- to chase -- and every square of margin is a square of shadow trailing her.
C.SkyTrailMargin = 0

-- How far around a player to hunt for invisible floors nobody is using, in
-- squares. Much larger than the patch, because this is not about the plane the
-- ship is flying on -- it is about the ones it left behind.
--
-- A floor is a world object and world objects are saved. Every build of this
-- feature that laid a wider plane, or trimmed it less eagerly, left its floors
-- in whatever world it was tested in, and they are still there: a black
-- blotch across a car park, seen in a screenshot after the plane itself was
-- already down to 25 squares. The ship's own record only remembers the last
-- flight, so the only way to clear the rest is to go and look.
C.SkyCleanRadius = 32

-- How far a player must move before that area is swept again. There is no
-- timer besides this: ground that has been swept has nothing left to find, and
-- ground that has not should not be made to wait.
C.SkyCleanStride = 20

-- Squares paved per tick. The plane is laid the way the landing search is
-- walked -- a cursor and a slice -- because a thousand addFloor calls in one
-- frame is not slow, it is the hard lock described in DEV_GUIDE.md under
-- "Slice any search that touches thousands of squares".
C.SkyTilesPerTick = 96

-- A ceiling on the plane, so a long flight cannot grow the list without
-- bound. Past this the squares furthest behind the ship are lifted first.
C.SkyMaxTiles = 40000

-- **There is one flight altitude and it is this one.** She is on the ground or
-- she is hovering; there is no climbing and no diving, and nothing anywhere in
-- the mod may ask for a different level.
--
-- It was 1 to 4 with a cruise of 3, and the menu said "Climb" and "Dive". In
-- play only the ground and level 1 ever behaved, so three of the four rungs
-- were an offer the ship could not keep -- and a control that appears to do
-- nothing is the thing this project keeps writing rules about.
--
-- Level 1 is also the one altitude the engine is *structurally* willing to
-- hold, which is worth knowing before anybody raises it again.
-- BaseVehicle.update() accepts a height when
--
--     sq != null && (sq.getFloor() != null || (sqB != null && sqB.getFloor() != null))
--
-- -- a floor at the level **or the one below**. At level 1 the one below is
-- Kentucky, so the ground itself satisfies the floor half of that test and the
-- sky plane only has to make the square at level 1 exist. At level 2 and above
-- the plane is the only thing holding her up, and every square of it has to
-- have been laid, and stay laid, before the engine will keep her there.
--
-- Level 0 is the ground and is never paved: a floor laid there would be a
-- floor laid on Kentucky.
--
-- **Revised 2026-09-24: one altitude still, and a higher one.** At level 1 a
-- two-storey building has walls at her own level and she drives into them. The
-- climb that made level 2 and up look impossible was the *climb*, not the
-- height: from the report, "take her up again" lifted her onto a floor the
-- physics had not been told about yet, she tipped back onto the level below,
-- and the old re-lift then teleported her upwards every tick with the state
-- still saying level 2 -- which is "stuck". Take-off now rises straight from
-- the ground to this level, smoothly, and hovers there until the engine is
-- actually holding her (TREK_Flight's ascent). Nothing changes level in flight.
--
-- The default, and the one the tests fly. The server owner picks the real one
-- from the sandbox page (C.flightLevel) -- Louisville has towers that no
-- sensible default clears.
C.FlightLevel = 5

-- The sandbox option's choices, as z levels. A level clears anything with that
-- many storeys or fewer: level 5 flies over a five-storey building.
C.FlightLevels = { 2, 3, 4, 5, 6, 8 }

--- The one altitude, as the server owner set it. Every process reads the same
--- sandbox value, so the server's check on `airborne` and the pilot's ascent
--- agree without a packet saying which.
function C.flightLevel()
    local ok, v = pcall(function()
        return SandboxVars.TrekShuttle and SandboxVars.TrekShuttle.FlightHeight
    end)
    v = ok and tonumber(v) or nil
    return (v and C.FlightLevels[math.floor(v)]) or C.FlightLevel
end

-- How high the tidy-up hunts for invisible floors left behind, in levels.
-- Deliberately *not* the flight level: a floor is a saved world object, and
-- the litter a flight left in somebody's world does not disappear because a
-- server owner lowered the ceiling afterwards. So it is the highest level any
-- setting can fly at, not the one in force.
C.SkyLitterTop = 8

-- The ascent and the descent. She is carried between the ground and her
-- flight level by moving the physics body a little every tick, eased at both
-- ends, rather than by one teleport -- so the crew see her rise and settle,
-- and so no floor is ever put *above* her while she passes it.
--
-- The renderer draws a vehicle at its physics height, not at its whole level
-- (ModelSlotRenderData.init, bci 101-139: centerOfMassY is origin.y minus the
-- level's own base), so a smooth change in the body is a smooth change on
-- screen.
C.FlightClimbLevelsPerSecond = 2
C.FlightClimbMinMs = 900

-- At the top she is held where she is, by the same per-tick placement, until
-- the plane under her is complete and this long has passed: a floor reaches
-- the physics engine a beat after it reaches the map (RecalcProperties ->
-- IsoChunk.checkPhysicsLater, and Bullet asks for the level when it next
-- steps). Letting go onto a floor the physics has not heard of yet is exactly
-- the tip-and-fall the climb used to produce.
C.FlightSettleMs = 600

-- After letting go, how long to watch that she stays up, and how far she may
-- sink (in levels) before that counts as the engine refusing the height.
C.FlightWatchMs = 900
C.FlightSinkTolerance = 0.3

-- Holds to try before giving up on the height and bringing her back down.
C.FlightSettleAttempts = 3

-- In flight, if the engine lets her fall off her level: how many times she is
-- carried back up, and how long between tries. After that she is left alone
-- and the pilot is told to set her down, instead of being teleported upward
-- every tick for ever -- which was the old "stuck".
C.FlightRecoverLimit = 3
C.FlightRecoverMs = 1500

-- The obstacle guard (TREK_Flight). Walls at her own level are looked for
-- from GuardFrom squares ahead of her centre -- her nose is two and a half
-- out -- to GuardReach, the way she is moving, and her top speed is cut by
-- GuardPerSquare for every square closer a wall is, down to GuardCrawl.
C.GuardFrom = 3
C.GuardReach = 14
C.GuardPerSquare = 8
C.GuardCrawl = 5

---------------------------------------------------------------------------
-- Flight: the shadow
---------------------------------------------------------------------------
-- A soft dark disc on the ground under her centre square, which is exactly the
-- square `F.land` sets her down on: the shadow *is* the landing marker.
--
-- It is drawn with vanilla's ground markers (getWorldMarkers, the tutorial's
-- call at client/Tutorial/Steps.lua:55), which draw per level being rendered
-- -- so a marker on the ground shows while the pilot is five levels up -- and
-- blend normally with a depth test, so black is a shadow and a building in
-- front of it hides it. Nothing is placed in the world and nothing is synced;
-- each client draws its own from the vehicle it can see.
--
-- The build 42 renderer accepts exactly one texture for these,
-- `circle_center`, and it is a ring: transparent in the middle, strongest
-- towards the rim. So the disc is several rings nested inside each other,
-- which fills the centre in.
C.ShadowTexture = "circle_center"
C.ShadowSize = 4.4            -- the outer ring, in the marker's own units (x0.69 = tiles of radius)
C.ShadowRings = { 1.0, 0.82, 0.64, 0.48, 0.34, 0.22, 0.12 }
C.ShadowAlpha = 0.55
-- Shown once her body is this far above the ground, in levels.
C.ShadowMinLevels = 0.3

-- Ticks to wait for the sky plane to appear under her before giving up on the
-- take-off.
C.FlightLiftTicks = 60

-- Degrees she may be off level before she is put right. She rests on an
-- invisible floor with real physics running, and a 1200kg box on a one-tile
-- shelf will tip if it is nudged -- she went over backwards in game.
--
-- This was 4, and it was measured against the wrong thing (see TREK_Flight's
-- keepLevel). Twenty now, for two reasons: a vehicle's suspension pitches it
-- several degrees under throttle and brakes, which is the engine drawing a
-- car rather than a ship falling over; and putting her right is a physics
-- teleport, which the pilot feels as a stutter. Going over backwards is
-- ninety degrees, so twenty is still nowhere near letting it happen.
C.FlightLevelTolerance = 20

-- The helm's flight speeds, as the vehicle's own top speed in the units
-- setMaxSpeed takes (the shuttle's script sets 70 on the ground).
--
-- Absolute figures, not multipliers, and that is a correction. They were
-- multipliers of a base of 30, capped at 0.6 of the server's SpeedLimit of
-- 70 -- which is 42, so the top three steps all clamped to exactly the same
